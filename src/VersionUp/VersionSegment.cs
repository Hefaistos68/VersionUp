namespace VersionUp
{
	/// <summary>
	/// Specifies the segment of the version to increment.
	/// </summary>
	public enum VersionSegment
	{
	    /// <summary>
	    /// The Major version segment.
	    /// </summary>
	    Major,

	    /// <summary>
	    /// The Minor version segment.
	    /// </summary>
	    Minor,

	    /// <summary>
	    /// The Build version segment.
	    /// </summary>
	    Build,

	    /// <summary>
	    /// The Revision version segment.
	    /// </summary>
	    Revision
	}
}
